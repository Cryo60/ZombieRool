logfile=OUT/('risen-combat-server.log' if risen else 'actor-combat-server.log' if actor_combat else 'actors-server.log' if actors else 'enemies-server.log' if enemies else 'delivery-server.log' if delivery else 'atmosphere-server.log' if atmosphere else 'buildables-server.log' if regression else 'server.log')
