(tags/'buildable_components.json').write_text('{"replace":false,"values":["minecraft:amethyst_shard"]}')
if actors:
    import shutil
    shutil.copytree(ROOT/'examples/stratholme/zombierool',world/'world/zombierool',dirs_exist_ok=True)
