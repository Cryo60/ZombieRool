(fixture/'pack.mcmeta').write_text('{"pack":{"pack_format":15,"description":"Buildable addon integration fixture"}}')
folder=fixture/'data/fixture/buildable_presets';folder.mkdir(parents=True,exist_ok=True)
(folder/'generator.json').write_text('{"name":"Datapack Generator","mode":"item","reward":{"item":"minecraft:clock","count":1,"nbt":"{CustomModelData:42}"},"parts":[{"id":"fixture:coil","item":"minecraft:copper_ingot","count":1}]}')
