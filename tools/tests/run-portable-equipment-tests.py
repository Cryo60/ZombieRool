name='MapRisenCombatTest' if risen else 'MapActorCombatTest' if actor_combat else 'MapActorsTest' if actors else 'EnemyEncountersTest' if enemies else 'MachineDeliveryTest' if delivery else 'MapAtmosphereGameplayTest' if atmosphere else 'BuildableGameplayTest' if regression else 'PortableEquipmentTest'
modid='risencombat' if risen else 'actorcombat' if actor_combat else 'actortests' if actors else 'enemytests' if enemies else 'deliverytests' if delivery else 'atmospheretests' if atmosphere else 'buildabletests' if regression else 'portabletests'
testdir=OUT/('test-mod-risen-combat' if risen else 'test-mod-actor-combat' if actor_combat else 'test-mod-actors' if actors else 'test-mod-enemies' if enemies else 'test-mod-delivery' if delivery else 'test-mod-atmosphere' if atmosphere else 'test-mod-buildables' if regression else 'test-mod')
compile([ROOT/f'tools/tests/{name}.java'],testdir,str(runtime)+';'+cp)
stale=testdir/'me/cryo/zombierool/gameplay/PortableEquipmentTest.class'
if stale.exists():stale.unlink()
meta=testdir/'META-INF';meta.mkdir(exist_ok=True);(meta/'mods.toml').write_text('modLoader="javafml"\nloaderVersion="[47,)"\nlicense="test"\n[[mods]]\nmodId="'+modid+'"\nversion="1"\ndisplayName="Equipment integration tests"\n')
world=OUT/('risen-combat-world-'+str(int(time.time())) if risen else 'actor-combat-verification-world-'+str(int(time.time())) if actor_combat else 'actors-world' if actors else 'enemies-world' if enemies else 'delivery-world' if delivery else 'atmosphere-world' if atmosphere else 'buildables-world' if regression else 'test-world');world.mkdir(exist_ok=True);(world/'eula.txt').write_text('eula=true\n');(world/'server.properties').write_text('online-mode=false\nserver-port=0\nlevel-type=minecraft:flat\nspawn-protection=0\nmax-tick-time=-1\nallow-flight=true\n')
